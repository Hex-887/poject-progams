if select == 1: #Программма 2.1
    
    #Блок вывода данных
    
    #ввод данных
    print ("Введите значение x, y, z:")
    x_1 = input("x = ")
    y_1 = input("y = ")
    z_1 = input("z = ")
    tz = int(input("Знаков после запятой: "))
    #небольшой костыль для правильного расчета выражения
    x = sp.sympify(x_1)
    y = sp.sympify(y_1)
    z = sp.sympify(z_1)


    #Блок вычислений
    
    t = ((2 * mt.cos(x - (mt.pi / 6))) / (0.5 + (mt.sin(y) ** 2))) * (1 + (z ** 2) / (3 - (z ** 2) / 5))
    tr = round(t, tz)
    print ("Результат вычислений: ", tr)

elif select == 2: #Программа 2.2
    print ("Программа вычисляет среднее арифметическое чисел A, B и C, вычисляющиеся по определенным формулам:")
    
    #Блок вывода данных
    
    #ввод данных
    print ("Введите значение a, b, c:")
