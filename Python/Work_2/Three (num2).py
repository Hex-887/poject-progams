
#введем строки

print ("Давайте зажигать елочку!")
countdown = input("Фразы через запятую три: ") #вводим данные


#подготовим данные к обработке

parts = countdown.split(',') #разделяем строки по запятой и записываем в массив
cd_cl = [] #создаем список для готовых к обработке строк
count = 0 #обьявляем счетчик для подсчета количества введенных строк
for p in parts: #цикл по всему массиву строк до нужного момента
    s = p.strip(".!?\t\n ").lower() #отчистим от лишних символов пробелов, табуляций, переносов строк и знаков препинания и приведем к нижнему регистру

    if s == "": #если строка пустая, то пропускаем ее
        continue

    cd_cl.append(s) #добавляем отфильтрованную строку в список и увеличиваем счетчик принятых строк на 1
    count += 1
    
    if len(cd_cl) > 3: #если строк больше трех, то выводим сообщение и завершаем программу
        print("Так не получится — фраз больше трёх.")
        exit()
if len(cd_cl) < 3: #проверим, что строк не меньше трех
    print("Так не получится — фраз меньше трёх.")
    exit()

#Обработанные данные проверяем на соответствие условиям задачи

